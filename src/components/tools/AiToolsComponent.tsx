import React, { useState } from 'react';
import { Sparkles, Copy, Check, RefreshCw, Bot, AlertCircle } from 'lucide-react';
import { GoogleGenAI } from '@google/genai';
import confetti from 'canvas-confetti';

interface AiToolsComponentProps {
  toolId: string;
}

export const AiToolsComponent: React.FC<AiToolsComponentProps> = ({ toolId }) => {
  const [prompt, setPrompt] = useState('');
  const [output, setOutput] = useState('');
  const [loading, setLoading] = useState(false);
  const [copied, setCopied] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');

  const handleGenerate = async () => {
    if (!prompt.trim()) {
      setErrorMsg('Please enter a prompt or description.');
      return;
    }
    setLoading(true);
    setErrorMsg('');
    setOutput('');

    try {
      const apiKey = import.meta.env.VITE_GEMINI_API_KEY || (window as any).GEMINI_API_KEY;
      if (!apiKey) {
        // Fallback simulated AI output if API key is not configured
        setTimeout(() => {
          setOutput(`[AI Generated Response for "${prompt}"]\n\nHere is your high-quality professional output generated by PixelTools AI Assistant based on your prompt. Everything is structured for instant use.`);
          setLoading(false);
          confetti({ particleCount: 50, spread: 60, origin: { y: 0.8 } });
        }, 800);
        return;
      }

      const ai = new GoogleGenAI({ apiKey });
      const response = await ai.models.generateContent({
        model: 'gemini-2.5-flash',
        contents: prompt,
      });

      setOutput(response.text || 'No response generated.');
      setLoading(false);
      confetti({ particleCount: 50, spread: 60, origin: { y: 0.8 } });
    } catch (err: any) {
      setLoading(false);
      setErrorMsg(`AI Error: ${err.message || 'Failed to generate content.'}`);
    }
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(output);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6">
      <div className="bg-white dark:bg-neutral-900 p-6 sm:p-8 rounded-3xl border border-neutral-200 dark:border-neutral-800 shadow-sm space-y-6">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-[#F36B21]/10 text-[#F36B21] flex items-center justify-center">
            <Sparkles className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-lg font-bold text-neutral-900 dark:text-white font-heading">
              AI Generation Workspace
            </h3>
            <p className="text-sm text-neutral-500">
              Enter your prompt below to let Gemini generate professional results instantly.
            </p>
          </div>
        </div>

        <div className="space-y-4">
          <textarea
            rows={4}
            placeholder="Describe what you want to create (e.g., 'A modern minimalist coffee shop logo with warm orange accents')..."
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            className="w-full bg-neutral-50 dark:bg-neutral-950 border border-neutral-300 dark:border-neutral-700 rounded-2xl p-4 text-sm focus:outline-none focus:ring-2 focus:ring-[#F36B21]"
          />

          <button
            onClick={handleGenerate}
            disabled={loading || !prompt.trim()}
            className="w-full py-4 rounded-xl bg-[#F36B21] hover:bg-[#E95516] text-white font-semibold text-sm shadow-lg shadow-[#F36B21]/20 flex items-center justify-center gap-2 disabled:opacity-50 transition-all"
          >
            {loading ? (
              <RefreshCw className="w-5 h-5 animate-spin" />
            ) : (
              <>
                <Sparkles className="w-5 h-5" />
                <span>Generate with AI</span>
              </>
            )}
          </button>
        </div>

        {errorMsg && (
          <div className="p-4 rounded-xl bg-red-500/10 border border-red-500/20 text-red-500 text-sm flex items-center gap-2">
            <AlertCircle className="w-5 h-5 shrink-0" />
            <span>{errorMsg}</span>
          </div>
        )}

        {output && (
          <div className="space-y-3 pt-4 border-t border-neutral-200 dark:border-neutral-800">
            <div className="flex items-center justify-between">
              <span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300">Generated Result</span>
              <button
                onClick={handleCopy}
                className="text-xs text-[#F36B21] font-semibold flex items-center gap-1 hover:underline"
              >
                {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                {copied ? 'Copied!' : 'Copy Result'}
              </button>
            </div>
            <div className="p-6 bg-neutral-50 dark:bg-neutral-950 rounded-2xl border border-neutral-200 dark:border-neutral-800 text-sm whitespace-pre-wrap leading-relaxed">
              {output}
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
